"""
What a typed prompt becomes before the loop runs: a slash command or a text prompt, then the
UserPromptSubmit hooks.

Ported from `reference/claude-code/src/utils/processUserInput/processUserInput.ts` ->
`processUserInput`, `processUserInputBase`, with `processTextPrompt.ts` -> `processTextPrompt` and
`processSlashCommand.tsx` -> `processSlashCommand` (its parse, unknown-command and prompt-command
branches). The REPL and headless share it through `QueryEngine.submit_message`.

* **Base.** Input starting with `/` goes to the slash-command path: a known prompt command (a
  skill) expands into its messages (`get_messages_for_prompt_slash_command`) and its attachments,
  whose `allowed-tools` and `model` then apply to the turn; `/name` that looks like a command but
  is none is answered "Unknown skill: …" and never queried; anything else (`/usr/bin/x`, an
  existing path) is a text prompt. A text prompt is the user's message, then the user-input
  attachments.
* **UserPromptSubmit**, on the raw input and only when the base would query: a blocking error
  drops everything said (upstream keeps only a UI warning); `continue: false` keeps the prompt
  and its attachments, adds "Operation stopped by hook", and does not query; hook context
  follows what was said.

The REPL runs its own local commands (`/plan`, `/pause`, …) before input reaches here, so the
slash path knows only the skills (`get_skill_tool_commands`). Not ported: images and pasted
contents, `bash` mode, bridge-safe commands, the ultraplan keyword, agent-mention logging and
OTel prompt events.
"""

from __future__ import annotations

import os
from collections.abc import Sequence
from dataclasses import dataclass, field
from typing import Any

from langchain_core.messages import HumanMessage

from app.utils.messages import Message
from app.utils.process_user_input.process_slash_command import (
    get_messages_for_prompt_slash_command,
    looks_like_command,
    parse_slash_input,
    unknown_skill_message,
)

#: `LOCAL_COMMAND_CAVEAT_TAG` and `createSyntheticUserCaveatMessage`'s text, verbatim.
LOCAL_COMMAND_CAVEAT_TAG = "local-command-caveat"
LOCAL_COMMAND_CAVEAT = (
    f"<{LOCAL_COMMAND_CAVEAT_TAG}>Caveat: The messages below were generated by the user while running local "
    "commands. DO NOT respond to these messages or otherwise consider them in your response unless the user "
    f"explicitly asks you to.</{LOCAL_COMMAND_CAVEAT_TAG}>"
)


@dataclass
class ProcessUserInputResult:
    """`ProcessUserInputBaseResult`, plus why a UserPromptSubmit hook stopped the turn."""

    messages: list[Message] = field(default_factory=list)
    should_query: bool = True
    allowed_tools: tuple[str, ...] = ()
    model: str | None = None
    #: Output for a turn that does not query (the unknown-command reply).
    result_text: str | None = None
    #: The blocking or stop text of a UserPromptSubmit hook that stopped the turn.
    stopped_reason: str | None = None


def create_synthetic_user_caveat_message() -> HumanMessage:
    """`createSyntheticUserCaveatMessage`."""
    return HumanMessage(content=LOCAL_COMMAND_CAVEAT, additional_kwargs={"is_meta": True})


def model_only_skill_message(name: str) -> str:
    """The reply to a typed skill that is not user-invocable (product name substituted)."""
    return (f"This skill can only be invoked by TDDAgents, not directly by users. Ask TDDAgents to use the "
            f'"{name}" skill for you.')


async def _attachments(context: Any, said: Sequence[Message], user_input: str) -> list[Message]:
    from app.utils.attachments import get_attachment_messages

    return await get_attachment_messages(context, said, user_input=user_input)


async def process_slash_command(
    input_string: str, context: Any, history: Sequence[Message], *, session_id: str = "", coordinator: bool = False
) -> ProcessUserInputResult | None:
    """
    `processSlashCommand` for the skills: the prompt command's turn, the unknown-command reply,
    or `None` when the input is a text prompt after all (not a command name, or an existing path).
    """
    parsed = parse_slash_input(input_string)
    if parsed is None:
        return None
    name, args = parsed
    registry = getattr(context, "skill_registry", None)
    command = registry.find_command(name) if registry is not None else None
    if command is None:
        if not looks_like_command(name) or os.path.exists(f"/{name}"):
            return None
        text = unknown_skill_message(name, args)
        return ProcessUserInputResult(
            messages=[create_synthetic_user_caveat_message(), HumanMessage(content=text)],
            should_query=False, result_text=text,
        )
    if not command.user_invocable:
        return ProcessUserInputResult(
            messages=[HumanMessage(content=f"/{name}"), HumanMessage(content=model_only_skill_message(name))],
            should_query=False, result_text=model_only_skill_message(name),
        )
    turn = get_messages_for_prompt_slash_command(command, args, session_id=session_id, coordinator=coordinator)
    said = [*history, *turn.messages]
    skill_text = str(turn.messages[-1].content)
    return ProcessUserInputResult(
        messages=[*turn.messages, *await _attachments(context, said, skill_text)],
        allowed_tools=turn.allowed_tools, model=turn.model,
    )


async def process_user_input_base(
    input_string: str,
    context: Any,
    history: Sequence[Message],
    *,
    user_messages: Sequence[Message] | None = None,
    skip_slash_commands: bool = False,
    session_id: str = "",
    coordinator: bool = False,
) -> ProcessUserInputResult:
    """`processUserInputBase`: the slash-command path, else `processTextPrompt`."""
    if not skip_slash_commands and input_string.startswith("/"):
        slash = await process_slash_command(
            input_string, context, history, session_id=session_id, coordinator=coordinator
        )
        if slash is not None:
            return slash
    said = list(user_messages) if user_messages is not None else [HumanMessage(content=input_string)]
    return ProcessUserInputResult(messages=[*said, *await _attachments(context, [*history, *said], input_string)])


async def process_user_input(
    input_string: str,
    context: Any,
    history: Sequence[Message],
    *,
    permission_mode: str,
    user_messages: Sequence[Message] | None = None,
    skip_slash_commands: bool = False,
    session_id: str = "",
    coordinator: bool = False,
) -> ProcessUserInputResult:
    """
    `processUserInput`: the base result, then the UserPromptSubmit hooks on the raw input.
    `user_messages` stands in for the plain user message (a resumed session's first turn).
    """
    from app.utils.session_start import process_user_prompt_submit_hooks

    result = await process_user_input_base(
        input_string, context, history, user_messages=user_messages,
        skip_slash_commands=skip_slash_commands, session_id=session_id, coordinator=coordinator,
    )
    if not result.should_query:
        return result
    hooks = await process_user_prompt_submit_hooks(context, input_string, permission_mode)
    if hooks.blocked_message is not None:
        return ProcessUserInputResult(should_query=False, allowed_tools=result.allowed_tools,
                                      stopped_reason=hooks.blocked_message)
    if hooks.stopped_message is not None:
        result.messages.extend(hooks.messages)
        result.messages.append(HumanMessage(content=hooks.stopped_message))
        result.should_query = False
        result.stopped_reason = hooks.stopped_message
        return result
    result.messages.extend(hooks.messages)
    return result



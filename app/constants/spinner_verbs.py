def get_spinner_verbs(settings: Mapping[str, Any] | None = None) -> list[str]:
    """`getSpinnerVerbs`: the list as the merged settings' `spinnerVerbs` shape it."""
    config = (settings or {}).get("spinnerVerbs")
    if not isinstance(config, Mapping):
        return list(SPINNER_VERBS)
    verbs = [str(v) for v in config.get("verbs") or ()]
    if config.get("mode") == "replace":
        return verbs if verbs else list(SPINNER_VERBS)
    return [*SPINNER_VERBS, *verbs]


